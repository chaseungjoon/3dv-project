"""Generate the per-variant env configs from experiments/configs/variants.yaml.

Every variant is the base config plus a few overrides. This script refuses any override
outside `allowed_keys` (the wrist terms), so a variant can never silently change anything
else. It also re-checks the written files against the base.

    python experiments/tools/make_configs.py          # write configs/env/*.yaml
    python experiments/tools/make_configs.py --check  # only verify the files on disk
"""
import argparse
import copy
import os
import sys

import yaml

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CFG_DIR = os.path.join(REPO, 'experiments', 'configs')
OUT_DIR = os.path.join(CFG_DIR, 'env')


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


def get_section(cfg, dotted):
    node = cfg
    for part in dotted.split('.'):
        node = node[part]
    return node


def flatten(d, prefix=''):
    out = {}
    for k, v in d.items():
        key = f'{prefix}.{k}' if prefix else str(k)
        if isinstance(v, dict):
            out.update(flatten(v, key))
        else:
            out[key] = v
    return out


def apply_overrides(base, overrides, allowed):
    cfg = copy.deepcopy(base)
    for section, values in (overrides or {}).items():
        if section not in allowed:
            raise ValueError(f'section "{section}" is not an allowed (wrist) section')
        target = get_section(cfg, section)
        for key, value in values.items():
            if key not in allowed[section]:
                raise ValueError(f'"{section}.{key}" is not a wrist key; T09 only changes wrist terms')
            if key not in target:
                raise KeyError(f'"{section}.{key}" does not exist in the base config')
            target[key] = value
    return cfg


def check_diff(base, cfg, allowed):
    allowed_flat = {f'{s}.{k}' for s, keys in allowed.items() for k in keys}
    fb, fc = flatten(base), flatten(cfg)
    if set(fb) != set(fc):
        raise ValueError(f'key sets differ: {sorted(set(fb) ^ set(fc))}')
    changed = {k: (fb[k], fc[k]) for k in fb if fb[k] != fc[k]}
    illegal = sorted(set(changed) - allowed_flat)
    if illegal:
        raise ValueError(f'non-wrist keys differ from base: {illegal}')
    return changed


def render(name, desc, base_rel, changed, cfg):
    lines = [
        '# AUTO-GENERATED by experiments/tools/make_configs.py -- do not edit by hand.',
        '# Edit experiments/configs/variants.yaml and re-run the script instead.',
        f'# variant : {name}',
        f'# desc    : {desc}',
        f'# base    : {base_rel}',
        '# changed : ' + (', '.join(f'{k}: {a} -> {b}' for k, (a, b) in sorted(changed.items())) or 'none'),
        '',
    ]
    return '\n'.join(lines) + yaml.safe_dump(cfg, default_flow_style=None, sort_keys=False, width=200)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='verify existing files only')
    args = parser.parse_args()

    spec = load_yaml(os.path.join(CFG_DIR, 'variants.yaml'))
    allowed = spec['allowed_keys']
    base = load_yaml(os.path.join(REPO, spec['base']))

    # The eval config is the default variant: same thresholds and windows for every variant.
    jobs = [(name, v.get('desc', ''), v.get('overrides')) for name, v in spec['variants'].items()]
    ev = spec['eval']
    src = spec['variants'][ev['source']]
    jobs.append((ev['name'], f"평가 전용: 모든 변형을 기본 손목 설정({ev['source']})으로 채점", src.get('overrides')))

    os.makedirs(OUT_DIR, exist_ok=True)
    ok = True
    for name, desc, overrides in jobs:
        cfg = apply_overrides(base, overrides, allowed)
        changed = check_diff(base, cfg, allowed)
        path = os.path.join(OUT_DIR, f'{name}.yaml')
        text = render(name, desc, spec['base'], changed, cfg)
        if args.check:
            if not os.path.isfile(path):
                print(f'[MISSING] {path}')
                ok = False
                continue
            on_disk = load_yaml(path)
            try:
                check_diff(base, on_disk, allowed)
            except ValueError as e:
                print(f'[BAD] {name}: {e}')
                ok = False
                continue
            if on_disk != cfg:
                print(f'[STALE] {name}: differs from variants.yaml, re-run make_configs.py')
                ok = False
                continue
            print(f'[OK] {name:12s} {len(changed)} wrist keys changed')
        else:
            with open(path, 'w') as f:
                f.write(text)
            print(f'[WROTE] {os.path.relpath(path, REPO)}  ({len(changed)} wrist keys changed)')
    if not ok:
        sys.exit(1)


if __name__ == '__main__':
    main()
