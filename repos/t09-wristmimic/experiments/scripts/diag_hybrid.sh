#!/usr/bin/env bash
# 진단 run: "들고 걷기" 구간이 이 환경에서 학습 가능한지 확인한다 (baseline 실험 아님, 결과 해석용).
#
# 왜: Phase 1 baseline은 항상 프레임 0에서 시작하고 프레임 ~47에서 끊겨서, 주전자를 들고(45~60)
#     걷는(60~120) 구간을 거의 연습하지 못했다. 시작 프레임을 랜덤으로 바꾸면 그 구간을 직접 연습한다.
#       - 그 구간을 해내면  -> 물리/환경은 정상, baseline 0%의 원인은 학습량/학습 구조
#       - 그래도 못 하면    -> 우리 환경(PhysX 버퍼 축소, torch 빌드 등)을 의심
#
# 바꾸는 것 (default.yaml 대비 이 4개뿐, 손목 설정은 그대로):
#   stateInit      Start -> Hybrid  (hybridInitProb 비율은 프레임 0, 나머지는 [0, 155-rolloutLength) 균등)
#   rolloutLength  300   -> 60      (300이면 155프레임 장면에서 랜덤 범위가 [0,1) = 항상 프레임 0이 된다)
#   hybridInitProb 0.1   (원본 값 유지)
#   physicalBufferSize 3 -> 1  (PSI 끔. baseline에서는 155 < rolloutLength(300)이라 PSI 코드가 항상 건너뛰어진다.
#                              rolloutLength를 줄이면 켜지는데, 원본 PSI 코드가 상태 332차원을 참조 358차원에
#                              넣으려다 RuntimeError로 죽는다. 1로 두면 baseline과 실질적으로 같은 동작)
# 참고: baseline 정책을 프레임 60, 90에서 시작하면 첫 행동에 주전자가 10~15 cm 튕겨 나간다. 진단 정책은
#   그렇지 않으므로(< 1 cm) 리셋/물리 문제가 아니라 그 상태를 학습한 적 없는 정책의 행동이다.
# 속도: Hybrid reset이 env마다 Python 루프라 epoch당 약 8 s (baseline 6 s).
#
# 사용법 (저장소 루트에서, tmux 안에서 권장):
#   bash experiments/scripts/diag_hybrid.sh           # 새로 학습 (기본 2000 epoch, 약 4~4.5시간) + 평가 (약 10분)
#   bash experiments/scripts/diag_hybrid.sh resume    # 중단된(Ctrl+C) 진단 run을 이어 학습 + 평가
#   bash experiments/scripts/diag_hybrid.sh eval      # 가장 최근 진단 run을 평가만 다시
# 환경변수: DIAG_EPOCHS(2000, 500의 배수), DIAG_ROLLOUT(60), DIAG_HYBRID_PROB(0.1),
#           START_FRAMES("45 60 90 120"), BASE_RUN(비교할 baseline run 폴더)
#
# 산출물은 본 실험과 섞이지 않게 _diag 폴더에만 쓴다:
#   experiments/configs/diag/diag_hybrid.yaml    학습 설정 (매번 default.yaml에서 생성)
#   experiments/runs/_diag/<run>/                학습 결과
#   experiments/results/_diag/eval/              평가 json/npz (det, stoch, det_start<N>)
#   experiments/results/_diag/SUMMARY.md         baseline vs 진단 run 비교표
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

MODE="${1:-new}"
DIAG_EPOCHS="${DIAG_EPOCHS:-2000}"
DIAG_ROLLOUT="${DIAG_ROLLOUT:-60}"
DIAG_HYBRID_PROB="${DIAG_HYBRID_PROB:-0.1}"
START_FRAMES="${START_FRAMES:-45 60 90 120}"
BASE_RUN="${BASE_RUN:-experiments/runs/default_s0_1004-175106}"
BASE_FINAL_EPOCH="${BASE_FINAL_EPOCH:-6000}"

VARIANT="diag_hybrid"
DIAG_CFG_DIR="experiments/configs/diag"
DIAG_RUNS="experiments/runs/_diag"
DIAG_OUT="experiments/results/_diag"

(( DIAG_EPOCHS % 500 == 0 )) || { echo "DIAG_EPOCHS는 500의 배수여야 합니다: $DIAG_EPOCHS" >&2; exit 2; }
[[ -d "$BASE_RUN/nn" ]] || { echo "baseline run이 없습니다: $BASE_RUN (BASE_RUN=...로 지정)" >&2; exit 1; }

# ---- 1. 진단 설정 생성 (default.yaml + 3개 키) ----
mkdir -p "$DIAG_CFG_DIR"
"$PY" - "$CFG_DIR/default.yaml" "$DIAG_CFG_DIR/$VARIANT.yaml" "$DIAG_ROLLOUT" "$DIAG_HYBRID_PROB" <<'EOF' || exit 1
import sys, yaml
src, dst, rollout, prob = sys.argv[1], sys.argv[2], int(sys.argv[3]), float(sys.argv[4])
cfg = yaml.safe_load(open(src))
env = cfg['env']
seq_len = 155
assert 0 < rollout < seq_len, f'rolloutLength must be < {seq_len} or Hybrid always starts at frame 0'
# physicalBufferSize 1: keeps the PSI block in _compute_reset disabled, as it effectively is in the baseline
changes = {'stateInit': 'Hybrid', 'rolloutLength': rollout, 'hybridInitProb': prob, 'physicalBufferSize': 1}
before = {k: env[k] for k in changes}
env.update(changes)
head = ['# AUTO-GENERATED by experiments/scripts/diag_hybrid.sh -- diagnostic only, NOT a T09 variant.',
        f'# base    : {src}',
        '# changed : ' + ', '.join(f'{k}: {before[k]} -> {v}' for k, v in changes.items()),
        f'# start frames: {prob:.0%} frame 0, rest uniform in [0, {seq_len - rollout}); episodes capped at {rollout} frames', '']
open(dst, 'w').write('\n'.join(head) + yaml.safe_dump(cfg, default_flow_style=None, sort_keys=False, width=200))
print(f'[diag] wrote {dst}: ' + ', '.join(f'{k} {before[k]} -> {v}' for k, v in changes.items()))
EOF

latest_diag_run() { ls -dt "$DIAG_RUNS"/*/ 2>/dev/null | head -1 | sed 's#/$##'; }

# ---- 2. 학습 ----
case "$MODE" in
  new)
    NAME="${VARIANT}_s0_$(date +%m%d-%H%M%S)"
    RUN="$DIAG_RUNS/$NAME"
    t09_log "진단 학습 시작: $NAME ($DIAG_EPOCHS epochs, rolloutLength=$DIAG_ROLLOUT, Hybrid p0=$DIAG_HYBRID_PROB)"
    CFG_DIR="$DIAG_CFG_DIR" RUNS_DIR="$DIAG_RUNS" RUN_NAME="$NAME" \
      bash experiments/scripts/train.sh "$VARIANT" 0 "$DIAG_EPOCHS" \
      || { t09_log "학습 중단/실패. 이어 하려면: bash $0 resume"; exit 1; }
    ;;
  resume)
    RUN="$(latest_diag_run)"
    [[ -n "$RUN" && -f "$RUN/run_meta.json" ]] || { echo "이어 할 진단 run이 없습니다 ($DIAG_RUNS)" >&2; exit 1; }
    NAME="$(basename "$RUN")"
    CKPT="$RUN/nn/${NAME}_latest.pth"
    [[ -f "$CKPT" ]] || { echo "체크포인트 없음: $CKPT" >&2; exit 1; }
    EPOCHS="$("$PY" -c "import json;print(json.load(open('$RUN/run_meta.json'))['epochs'])")"
    t09_log "진단 학습 이어 하기: $NAME <- $CKPT (목표 $EPOCHS epoch)"
    CFG_DIR="$DIAG_CFG_DIR" RUNS_DIR="$DIAG_RUNS" RUN_NAME="$NAME" RESUME_FROM="$CKPT" \
      bash experiments/scripts/train.sh "$VARIANT" 0 "$EPOCHS" \
      || { t09_log "학습 중단/실패. 이어 하려면: bash $0 resume"; exit 1; }
    DIAG_EPOCHS="$EPOCHS"
    ;;
  eval)
    RUN="$(latest_diag_run)"
    [[ -n "$RUN" ]] || { echo "평가할 진단 run이 없습니다 ($DIAG_RUNS)" >&2; exit 1; }
    DIAG_EPOCHS="$("$PY" -c "import json;print(json.load(open('$RUN/run_meta.json'))['epochs'])")"
    ;;
  *)
    echo "사용법: bash $0 [new|resume|eval]" >&2; exit 2 ;;
esac

# ---- 3. 평가 ----
# (a) 표준 평가: 프레임 0부터 끝까지, baseline과 같은 채점 설정(eval_default.yaml). 모든 체크포인트.
t09_log "평가 1/3: 표준 (프레임 0 시작) - 결정적 8 env, 모든 체크포인트"
"$PY" experiments/tools/evaluate.py --run_dir "$RUN" --which all --mode det --out_dir "$DIAG_OUT/eval" \
   --motion_file "$SCENE" --robot_type "$ROBOT" || exit 1
t09_log "평가 2/3: 표준 (프레임 0 시작) - 확률적 32 env, 모든 체크포인트"
"$PY" experiments/tools/evaluate.py --run_dir "$RUN" --which all --mode stoch --out_dir "$DIAG_OUT/eval" \
   --motion_file "$SCENE" --robot_type "$ROBOT" || exit 1

# (b) 중간 시작 평가: 프레임 N의 참조 자세(주전자 포함)에서 시작해 끝까지. 진단 run과 baseline 둘 다.
#     baseline은 같은 epoch($DIAG_EPOCHS)과 마지막 epoch($BASE_FINAL_EPOCH).
for F in $START_FRAMES; do
  t09_log "평가 3/3: 프레임 $F 에서 시작 - 결정적 8 env (진단 epoch $DIAG_EPOCHS, baseline epoch $DIAG_EPOCHS/$BASE_FINAL_EPOCH)"
  "$PY" experiments/tools/evaluate.py --run_dir "$RUN" "$BASE_RUN" --epochs "$DIAG_EPOCHS,$BASE_FINAL_EPOCH" \
     --mode det --start_frame "$F" --out_dir "$DIAG_OUT/eval" \
     --motion_file "$SCENE" --robot_type "$ROBOT" || exit 1
done

# ---- 4. 요약 ----
"$PY" experiments/tools/diag_summary.py --diag_run "$RUN" --base_run "$BASE_RUN" \
   --epoch "$DIAG_EPOCHS" --base_final_epoch "$BASE_FINAL_EPOCH" --starts 0 $START_FRAMES \
   --diag_eval "$DIAG_OUT/eval" --out "$DIAG_OUT/SUMMARY.md" || exit 1
t09_log "진단 완료. 요약: $DIAG_OUT/SUMMARY.md  (학습: $RUN)"
