"""STATUS (2026-11-17, fix-2 investigation): NEGATIVE. 9-11 mm fingers seemed to hold the book only because
thick capsules jam into each other (~300 N in free air); with intra-hand collisions off: 0/32 holds, same as 5 mm.
See iterations/fix-2/ITERATION.md section 1. Kept as a tool, not used by any iteration.

Write a humanoid MJCF whose finger collision capsules have a different radius (CPU, instant).

    python environment_iteration/src/tools/hand_asset.py --radius 0.009 \
        --src mjcf/mocap_parahome_boxhand_histphase.xml --out mjcf/mocap_parahome_boxhand_histphase_fix2.xml

The upstream hand fingers are capsules of radius 5 mm (1 cm thick fingers). The ParaHome reference stores finger
JOINT centres of a real hand, whose finger pads lie ~8-10 mm from the bone. With 5 mm capsules the demonstrated
pinch leaves the thumb ~7 mm short of the book, so nothing squeezes it (src/probes/grip.py, fix-2 ITERATION.md).
Only the 38 finger capsules (size="0.005", 19 per hand) change; their density is scaled by (r0/r)^2 so each finger
segment keeps its mass (the cylinder part; caps differ slightly), i.e. only the contact geometry changes.
Paths are relative to skillmimic/data/assets. Refuses to overwrite an existing file (assets are never edited).
"""
import argparse
import os
import re
import sys

ASSETS = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "skillmimic", "data", "assets"))
R0 = 0.005


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--radius", type=float, required=True)
    p.add_argument("--src", default="mjcf/mocap_parahome_boxhand_histphase.xml")
    p.add_argument("--out", required=True)
    p.add_argument("--force", action="store_true", help="overwrite (only for scratch probe assets)")
    a = p.parse_args()
    src, out = os.path.join(ASSETS, a.src), os.path.join(ASSETS, a.out)
    if os.path.exists(out) and not a.force:
        sys.exit(f"{out} exists; assets are never overwritten (pick a new name)")
    txt = open(src).read()
    pat = re.compile(r'<geom type="capsule"([^>]*?)density="([0-9.]+)"([^>]*?)size="0\.005"')
    n = 0

    def sub(m):
        nonlocal n
        n += 1
        dens = float(m.group(2)) * (R0 / a.radius) ** 2
        return f'<geom type="capsule"{m.group(1)}density="{dens:.1f}"{m.group(3)}size="{a.radius:g}"'
    new = pat.sub(sub, txt)
    if n != 38:
        sys.exit(f"expected 38 finger capsules, matched {n}; the source asset is not the one this tool knows")
    header = (f"<!-- [3dv] generated by environment_iteration/src/tools/hand_asset.py from {a.src}: finger capsule "
              f"radius {R0} -> {a.radius} m (38 capsules), density scaled to keep segment mass -->\n")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(header + new)
    print(f"[hand_asset] {a.out}: {n} finger capsules r={a.radius} (from {a.src})")


if __name__ == "__main__":
    main()
