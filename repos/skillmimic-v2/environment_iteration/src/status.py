"""Regenerate the auto block of environment_iteration/STATUS.md (cumulative results of every iteration). CPU, instant.

    python environment_iteration/src/status.py            # rewrite the block between the AUTO-STATUS markers
    python environment_iteration/src/status.py --print    # print it only

Only the text between `<!-- AUTO-STATUS:BEGIN -->` and `<!-- AUTO-STATUS:END -->` is replaced; everything else in
STATUS.md (current iteration, phase, next action, decision log) is written by the agent / human.
Reads: iterations/*/iteration.json, run checkpoints, iterations/*/analysis/e<budget>/summary.json, the train lock.
"""
import datetime
import os
import sys

SRC = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SRC)
import iterlib as L  # noqa: E402

BEGIN, END = "<!-- AUTO-STATUS:BEGIN -->", "<!-- AUTO-STATUS:END -->"
LOCK_INFO = os.path.join(L.EI, ".train.lock.info")


def pct(v):
    return "-" if v is None else f"{100 * v:.0f}%"


def training_now():
    """(iteration, started) if scripts/train.sh holds the GPU lock, else None."""
    info = L.read_json(LOCK_INFO)
    if not info:
        return None
    try:
        os.kill(int(info["pid"]), 0)
    except (OSError, KeyError, ValueError):
        return None
    return info


def state_of(name, budget):
    it = L.load(name)
    P = L.paths(name)
    ep = L.latest_epoch(P["run_dir"])
    tr = training_now()
    s = L.read_json(os.path.join(P["analysis_dir"], f"e{budget}", "summary.json"))
    if tr and tr.get("iteration") == name:
        st = f"TRAINING ({ep}/{budget})"
    elif ep == 0:
        st = "defined (not trained)"
    elif ep < budget:
        st = f"stopped at {ep}/{budget} (re-run train.sh)"
    elif s is None:
        st = "trained, needs eval.sh"
    else:
        st = "analyzed"
    if it.get("imported") and ep >= budget:
        st = f"imported ({it['imported'].get('trained_epochs', ep)} ep), " + st
    return it, st, s


def block():
    pr = L.protocol()
    budget = pr["train"]["epochs"]
    tgt = pr["target"]
    rows = ["| iteration | parent | change | state | task success (stoch, 95% CI) | perturbed | paper | lift | "
            "progress | fell in clip | first failure (top modes @ median frame) | late events (median frame) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    best = None
    for name in L.list_iterations():
        it, st, s = state_of(name, budget)
        cells = (s or {}).get("cells", {})
        g = cells.get(tgt["cell"], {}).get("aggregate", {})
        gp = cells.get("stoch_perturb", {}).get("aggregate", {})
        ci = g.get("task_success_ci95")
        ts = "-" if not g else f"**{pct(g.get('task_success'))}** ({100 * ci[0]:.0f}-{100 * ci[1]:.0f}%)"
        modes = cells.get(tgt["cell"], {}).get("modes", {})
        top = ", ".join(f"{m} {100 * v['frac']:.0f}% @{v['first_bad_median']:.0f}"
                        for m, v in sorted(modes.items(), key=lambda x: -x[1]["n"])[:3]) or "-"
        ev = cells.get(tgt["cell"], {}).get("events", {})
        late = ", ".join(f"{k} {pct(ev[k]['frac'])} @{ev[k]['median']:.0f}" for k in ("drop", "fall")
                         if ev.get(k) and ev[k].get("median") is not None) or "-"
        rows.append(f"| {name} | {it.get('parent') or '-'} | {it.get('summary', '')} | {st} | {ts} | "
                    f"{pct(gp.get('task_success')) if gp else '-'} | {pct(g.get('paper_success')) if g else '-'} | "
                    f"{pct(g.get('lift_success')) if g else '-'} | {pct(g.get('task_progress')) if g else '-'} | "
                    f"{pct(g.get('fell_in_clip')) if g else '-'} | {top} | {late} |")
        if g and (best is None or g["task_success"] > best[1]):
            best = (name, g["task_success"])
    tr = training_now()
    now = datetime.datetime.now().astimezone().isoformat(timespec="minutes")
    head = [f"_Auto-generated by `src/status.py` at {now}. Protocol v{pr['version']}: {budget} epochs x "
            f"{pr['train']['num_envs']} envs, seed {pr['train']['seed']}; evaluated at epoch {budget}. "
            f"Target: {tgt['metric']} >= {100 * tgt['threshold']:.0f}% in `{tgt['cell']}` (96 episodes)._", ""]
    if tr:
        head += [f"**GPU busy: `{tr.get('iteration')}` is training (pid {tr.get('pid')}, since {tr.get('started')}). "
                 f"Do not run GPU jobs or edit files that iteration depends on.**", ""]
    if best:
        head += [f"Best so far: **{best[0]}** with {pct(best[1])} task success "
                 f"({'TARGET REACHED' if best[1] >= tgt['threshold'] else 'target not reached'}).", ""]
    return "\n".join(head + rows)


def main():
    text = block()
    if "--print" in sys.argv:
        print(text)
        return
    path = os.path.join(os.path.dirname(L.ITER_DIR), "STATUS.md") if L.TEST_MODE else os.path.join(L.EI, "STATUS.md")
    cur = open(path).read() if os.path.isfile(path) else f"# Status\n\n{BEGIN}\n{END}\n"
    if BEGIN not in cur or END not in cur:
        sys.exit(f"{path}: markers {BEGIN} / {END} missing; restore them around the results section")
    a, b = cur.index(BEGIN) + len(BEGIN), cur.index(END)
    new = cur[:a] + "\n" + text + "\n" + cur[b:]
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(new)
    os.replace(tmp, path)
    print(f"[status] {L.rel(path)} updated ({len(L.list_iterations())} iteration(s))")


if __name__ == "__main__":
    main()
